async function seed() {
  const existing = await dbGet("SELECT id FROM global_orientation_tests LIMIT 1");
  if (existing) {
    console.log("Seed skipped: database already contains demo data");
    return;
  }

  const test = await dbRun(
    "INSERT INTO global_orientation_tests (title, description) VALUES (?, ?)",
    ["Входной профориентационный тест", "Единый стартовый тест платформы для первичной диагностики и маршрутизации."]
  );

  for (const [index, question] of testQuestions.entries()) {
    const insertedQuestion = await dbRun(
      "INSERT INTO global_test_questions (test_id, position, text, hint) VALUES (?, ?, ?, ?)",
      [test.id, index + 1, question.text, question.hint]
    );
    for (const [text, points, tags] of question.answers) {
      await dbRun(
        "INSERT INTO global_test_answers (question_id, text, points, tags_json) VALUES (?, ?, ?, ?)",
        [insertedQuestion.id, text, points, JSON.stringify(tags)]
      );
    }
  }

  for (const [code, title, description, tags] of profiles) {
    await dbRun(
      "INSERT INTO global_result_profiles (code, title, description, primary_tags_json) VALUES (?, ?, ?, ?)",
      [code, title, description, JSON.stringify(tags)]
    );
  }

  for (const enterprise of enterprises) {
    const insertedEnterprise = await dbRun(
      "INSERT INTO enterprises (code, name, sector, city, description, reason_template, tags_json) VALUES (?, ?, ?, ?, ?, ?, ?)",
      [enterprise.code, enterprise.name, enterprise.sector, enterprise.city, enterprise.description, enterprise.reason, JSON.stringify(enterprise.tags)]
    );

    for (const [title, description, competencies] of enterprise.professions) {
      await dbRun(
        "INSERT INTO enterprise_professions (enterprise_id, title, description, competencies_json) VALUES (?, ?, ?, ?)",
        [insertedEnterprise.id, title, description, JSON.stringify(competencies)]
      );
    }

    const scenario = await dbRun(
      "INSERT INTO enterprise_game_scenarios (enterprise_id, title, description) VALUES (?, ?, ?)",
      [insertedEnterprise.id, `Сценарий: ${enterprise.name}`, "Профориентационный квест предприятия."]
    );

    for (const [index, task] of enterprise.scenario.entries()) {
      const [title, prompt, visual, feedback, answers] = task;
      const question = await dbRun(
        "INSERT INTO enterprise_game_questions (scenario_id, position, title, prompt, visual_json, feedback) VALUES (?, ?, ?, ?, ?, ?)",
        [scenario.id, index + 1, title, prompt, JSON.stringify(visual), feedback]
      );
      await dbRun(
        "INSERT INTO enterprise_game_tasks (question_id, task_type, payload_json) VALUES (?, ?, ?)",
        [question.id, "choice_with_visual", JSON.stringify({ visual })]
      );
      for (const [text, points, isPreferred] of answers) {
        await dbRun(
          "INSERT INTO enterprise_game_answers (question_id, text, points, is_preferred) VALUES (?, ?, ?, ?)",
          [question.id, text, points, isPreferred]
        );
      }
    }
  }

  const counts = await dbAll("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name");
  console.log(`Seed completed: ${counts.length} tables ready`);
}

seed()
  .then(async () => closeDb())
  .catch(async (error) => {
    console.error(error);
    await closeDb();
    process.exit(1);
  });
