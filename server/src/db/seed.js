const alternateRoles = roleTypes.map((role) => role.code);

function makeQuestion(roleCode, index, [text, primary, secondary, tertiary]) {
  const primaryRoleIndex = alternateRoles.indexOf(roleCode);
  const secondaryRole = alternateRoles[(primaryRoleIndex + 1 + index) % alternateRoles.length];
  const tertiaryRole = alternateRoles[(primaryRoleIndex + 3 + index) % alternateRoles.length];

  return {
    text,
    hint: `Визуальный вопрос ${index + 1}/4 для типа «${roleTypes.find((role) => role.code === roleCode).title}».`,
    answers: [
      [primary, 3, { [roleCode]: 3, visual_analysis: 1 }],
      [secondary, 2, { [secondaryRole]: 2 }],
      [tertiary, 1, { [tertiaryRole]: 1 }]
    ]
  };
}

const testQuestions = visualQuestionTemplates.flatMap((group) =>
  group.questions.map((question, index) => makeQuestion(group.role, index, question))
);

